package practice.week3;

public class pattern {
    static void main(String[] args) {

        for(int i=1;i<=5;i++){
            //padding
            for(int j=i;j<5;j++) System.out.print(" ");
            //stars
            for(int j=1;j<=5;j++) System.out.print("*");
            System.out.println();


        }
    }
}
